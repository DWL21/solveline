export function normalizeNarrative(text, id) {
  for (const [before, after] of replacements[id] ?? []) text = text.replaceAll(before, after);
  // 최종 과제의 관용적 문장만 바꾸고 문제 속 프로그램의 동작은 보존한다.
  return text
    .replace(/구하는 프로그램을 작성하라\./g, '구해 반환하는 solution 함수를 완성해 주세요.')
    .replace(/계산하는 프로그램을 작성하라\./g, '계산해 반환하는 solution 함수를 완성해 주세요.')
    .replace(/출력하는 프로그램을 작성하라\./g, '반환하는 solution 함수를 완성해 주세요.')
    .replace(/구하는 프로그램을 작성하여라\./g, '구해 반환하는 solution 함수를 완성해 주세요.')
    .replace(/계산하는 프로그램을 작성하여라\./g, '계산해 반환하는 solution 함수를 완성해 주세요.')
    .replace(/구하는 프로그램을 작성하자\./g, '구해 반환하는 solution 함수를 완성해 주세요.');
}
